hl.config({
    input = {
        kb_layout  = "us, in, ara",
        kb_variant = ", mal_enhanced, ",
        kb_model   = "",
        kb_options = "grp:alt_shift_toggle",
        kb_rules   = "",
        numlock_by_default = true,

        follow_mouse = 1,

        sensitivity = 0, -- -1.0 - 1.0, 0 means no modification.

        touchpad = {
            natural_scroll = false,
        },
    },
    cursor  = {
      no_warps = true
    }

})


